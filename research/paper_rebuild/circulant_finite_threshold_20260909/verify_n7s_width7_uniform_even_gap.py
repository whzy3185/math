def cycle_block(mask: int) -> np.ndarray:
    B = np.zeros((7,7), dtype=np.int64)
    for i in range(7):
        sig = -1 if ((mask >> i) & 1) else 1
        j = (i + 1) % 7
        B[i,j] = B[j,i] = sig
    return B


def strip_matrix(transitions):
    states = [0]
    for d in transitions:
        states.append(states[-1] ^ d)
    L = len(states)
    M = np.zeros((7*L,7*L), dtype=np.int64)
    I = np.eye(7, dtype=np.int64)
    for j, state in enumerate(states):
        M[7*j:7*j+7,7*j:7*j+7] = cycle_block(state)
        if j+1 < L:
            M[7*j:7*j+7,7*j+7:7*j+14] = I
            M[7*j+7:7*j+14,7*j:7*j+7] = I
    return M


def reduced_matrix(d: int, e: int, g: int, boundary=6):
    transitions = [127]*3 + [d] + [127]*g + [e] + [127]*3
    M = strip_matrix(transitions)
    Q = M @ M - 8*np.eye(M.shape[0], dtype=np.int64)
    L = M.shape[0] // 7
    P = np.zeros((7*L, 86), dtype=np.int64)
    for j in range(boundary):
        P[7*j:7*j+7,7*j:7*j+7] = np.eye(7, dtype=np.int64)
    for off,j in enumerate(range(L-boundary,L)):
        col = 42 + 7*off
        P[7*j:7*j+7,col:col+7] = np.eye(7, dtype=np.int64)
    v = VCRIT[d]
    for j in range(boundary,L-boundary):
        P[7*j:7*j+7,84 + ((j-boundary)&1)] = v
    return P.T @ Q @ P


